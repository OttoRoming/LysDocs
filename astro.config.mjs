/** @param {string} value */
const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const systemLinkPattern = new RegExp(
	`^/(?:${Object.values(systemCategories)
		.map(({ path }) => escapeRegExp(path))
		.join("|")})/[^/]+/?$`,
);

